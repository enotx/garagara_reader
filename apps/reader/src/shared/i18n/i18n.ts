const MESSAGES: Record<AppLanguage, Record<MessageKey, string>> = { zh, en, ja };

export type TranslateParams = Record<string, string | number>;
export type Translate = (key: MessageKey, params?: TranslateParams) => string;

function interpolate(template: string, params?: TranslateParams): string {
  if (!params) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined ? match : String(value);
  });
}

export function translate(
  language: AppLanguage,
  key: MessageKey,
  params?: TranslateParams,
): string {
  return interpolate(MESSAGES[language]?.[key] ?? MESSAGES.zh[key], params);
}

export function translator(language: AppLanguage): Translate {
  return (key, params) => translate(language, key, params);
}

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === 'zh' || value === 'en' || value === 'ja';
}

export function localeFor(language: AppLanguage): string {
  if (language === 'en') {
    return 'en-US';
  }
  if (language === 'ja') {
    return 'ja-JP';
  }
  return 'zh-CN';
}
